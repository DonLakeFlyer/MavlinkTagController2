"""End-to-end tests: simulator IQ → STFT → fold_detect.

Verifies that the complete detection pipeline recovers pulsed-CW signals
generated by the simulator using real Telonics VHF collar parameters:
  - tp  = 15 ms  (pulse width)
  - tip = 2.0 s  (resting rate)  / 1.333 s (moving rate)
  - fs  = 3840 Hz (post-decimation sample rate)

Each test generates a full K-fold IQ segment in-process (no sockets), runs
the STFT + fold_detect chain, and checks the detection result.
"""

import numpy as np
import pytest

import pulse_detector
from pulse_detector import (
    build_hypothesis_indices,
    build_weighting_matrix,
    compute_segment_samples,
    compute_stft_power,
    fold_detect,
)
from iq_simulator import SimConfig, TagSignal, generate_packet

# ---------------------------------------------------------------------------
# Physical constants
# ---------------------------------------------------------------------------
FS = 3840            # Post-decimation sample rate (Hz)
TP = 0.015           # Pulse width (s)
TIP_REST = 2.0       # Resting inter-pulse interval (s)
TIP_MOVE = 1.333     # Moving inter-pulse interval (s)
PF = 1e-6            # False-alarm probability

# STFT geometry (mirrors pulse_detector main())
N_W = int(np.ceil(TP * FS))               # 58 samples
N_OL = N_W // 2                            # 29 samples
N_WS = N_W - N_OL                          # 29 samples (window step)
N_EXACT = TIP_REST * FS / N_WS            # fractional PRI in windows
N = int(np.floor(N_EXACT))                # integer PRI (resting rate)
N_EXACT_MOVE = TIP_MOVE * FS / N_WS
N_MOVE = int(np.floor(N_EXACT_MOVE))      # integer PRI (moving rate)

# Spectral weighting matrix (computed once for all tests)
W, Wf = build_weighting_matrix(N_W, FS)
NFFT = W.shape[1]

# ---------------------------------------------------------------------------
# Shared EVT cache pool — keyed by (K, N_B) so single-rate and dual-rate
# configurations get independent EVT thresholds.
# ---------------------------------------------------------------------------
_evt_pool: dict[tuple, dict] = {}


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def _fold_offsets(K: int, tip: float = TIP_REST) -> np.ndarray:
    N_exact = tip * FS / N_WS
    return np.round(np.arange(K) * N_exact).astype(int)


def _generate_segment(K: int, snr_db: float, freq_offset_hz: float = 0.0,
                      tip: float = TIP_REST, seed: int = 42) -> np.ndarray:
    """Generate a continuous IQ segment covering K pulse intervals."""
    N_A_exact = tip * FS / N_WS
    samples_needed = compute_segment_samples(N_WS, N_OL, K, N_A_exact)

    cfg = SimConfig(
        sample_rate=FS,
        samples_per_packet=samples_needed,
        noise_power_dbfs=-40.0,
        tags=[TagSignal(
            freq_offset_hz=freq_offset_hz,
            snr_db=snr_db,
            tp=TP,
            tip=tip,
        )],
        seed=seed,
    )
    rng = np.random.default_rng(cfg.seed)
    return generate_packet(cfg, sample_offset=0, rng=rng, telem_state=None)


def _run_detect(K: int, snr_db: float, freq_offset_hz: float = 0.0,
                tip: float = TIP_REST, seed: int = 42,
                detection_margin: float = 0.90):
    """Full pipeline: generate IQ → STFT → fold_detect. Returns fold_detect output."""
    old_K = pulse_detector.K
    pulse_detector.K = K
    try:
        N_A_exact = tip * FS / N_WS
        fo = _fold_offsets(K, tip)
        samples_needed = compute_segment_samples(N_WS, N_OL, K, N_A_exact)
        iq = _generate_segment(K, snr_db, freq_offset_hz, tip, seed)

        power, n_win = compute_stft_power(iq, N_W, N_OL, NFFT, W=W)

        # Per-(K, N_B) EVT cache so different configurations get independent thresholds
        cache = _evt_pool.setdefault((K, None), {})

        return fold_detect(
            power, N, PF, FS, NFFT, N_W, N_OL, samples_needed,
            cache,
            fold_offsets=fo,
            W=W, Wf=Wf,
            detection_margin=detection_margin,
        )
    finally:
        pulse_detector.K = old_K


# ===================================================================
# K = 5 (default fold count)
# ===================================================================
class TestSingleRateK5:
    K = 5

    def test_strong_signal_detected(self):
        detections, _, _ = _run_detect(self.K, snr_db=25.0)
        assert len(detections) >= 1, "Strong signal (25 dB) should be detected"

    def test_strong_signal_snr_reasonable(self):
        detections, _, _ = _run_detect(self.K, snr_db=25.0)
        best = max(detections, key=lambda d: d[1])
        assert best[1] > 10.0, f"Detected SNR {best[1]:.1f} dB unexpectedly low"

    def test_strong_signal_frequency_accuracy(self):
        """Two signals at different offsets should produce detections
        separated by the correct frequency difference."""
        d1, _, _ = _run_detect(self.K, snr_db=25.0, freq_offset_hz=0.0, seed=50)
        d2, _, _ = _run_detect(self.K, snr_db=25.0, freq_offset_hz=200.0, seed=50)
        assert len(d1) >= 1 and len(d2) >= 1
        f1 = max(d1, key=lambda d: d[1])[0]
        f2 = max(d2, key=lambda d: d[1])[0]
        freq_diff = f2 - f1
        bin_width = FS / NFFT
        assert abs(freq_diff - 200.0) < 2 * bin_width, (
            f"Frequency difference {freq_diff:.1f} Hz, expected ~200 Hz "
            f"(tolerance {2*bin_width:.1f} Hz)")

    def test_noise_only_no_detection(self):
        detections, noise_psd, _ = _run_detect(self.K, snr_db=-np.inf, seed=99)
        assert len(detections) == 0, "Noise-only segment should produce no detections"
        assert np.isfinite(noise_psd), "Noise PSD should be finite"

    def test_moderate_signal_detected(self):
        detections, _, _ = _run_detect(self.K, snr_db=12.0, seed=7)
        assert len(detections) >= 1, "Moderate signal (12 dB) should be detected with K=5"

    def test_fold_info_present(self):
        detections, _, _ = _run_detect(self.K, snr_db=25.0)
        assert len(detections) >= 1
        assert 'max_fold_fraction' in detections[0].fold_info
        assert 'fold_snrs' in detections[0].fold_info
        assert len(detections[0].fold_info['fold_snrs']) == self.K

    def test_negative_freq_offset(self):
        """A negative offset should produce a detection at a lower
        frequency than a zero-offset signal (modulo spectral wrapping)."""
        d0, _, _ = _run_detect(self.K, snr_db=20.0, freq_offset_hz=0.0, seed=60)
        dn, _, _ = _run_detect(self.K, snr_db=20.0, freq_offset_hz=-500.0, seed=60)
        assert len(d0) >= 1 and len(dn) >= 1
        f0 = max(d0, key=lambda d: d[1])[0]
        fn = max(dn, key=lambda d: d[1])[0]
        raw_diff = fn - f0
        # Wrap to [-FS/2, FS/2) to handle spectral boundary crossing
        wrapped_diff = ((raw_diff + FS / 2) % FS) - FS / 2
        bin_width = FS / NFFT
        assert abs(wrapped_diff - (-500.0)) < 2 * bin_width, (
            f"Wrapped frequency shift {wrapped_diff:.1f} Hz, expected ~-500 Hz")

    def test_detection_margin_tight(self):
        """Tight margin (0.99) should still detect a strong signal."""
        detections, _, _ = _run_detect(self.K, snr_db=25.0, detection_margin=0.99)
        assert len(detections) >= 1

    def test_reproducibility(self):
        d1, _, _ = _run_detect(self.K, snr_db=20.0, seed=123)
        d2, _, _ = _run_detect(self.K, snr_db=20.0, seed=123)
        assert len(d1) == len(d2)
        if d1:
            assert d1[0][0] == pytest.approx(d2[0][0])
            assert d1[0][1] == pytest.approx(d2[0][1])


