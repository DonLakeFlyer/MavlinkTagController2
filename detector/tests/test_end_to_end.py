class TestSingleRateK5:
    K = 5

    def test_strong_signal_detected(self):
        detections, _, _ = _run_detect(self.K, snr_db=25.0)
        assert len(detections) >= 1, "Strong signal (25 dB) should be detected"

    def test_strong_signal_snr_reasonable(self):
        detections, _, _ = _run_detect(self.K, snr_db=25.0)
        best = max(detections, key=lambda d: d[1])
        assert best[1] > 10.0, f"Detected SNR {best[1]:.1f} dB unexpectedly low"

    def test_strong_signal_frequency_accuracy(self):
        """Two signals at different offsets should produce detections
        separated by the correct frequency difference."""
        d1, _, _ = _run_detect(self.K, snr_db=25.0, freq_offset_hz=0.0, seed=50)
        d2, _, _ = _run_detect(self.K, snr_db=25.0, freq_offset_hz=200.0, seed=50)
        assert len(d1) >= 1 and len(d2) >= 1
        f1 = max(d1, key=lambda d: d[1])[0]
        f2 = max(d2, key=lambda d: d[1])[0]
        freq_diff = f2 - f1
        bin_width = FS / NFFT
        assert abs(freq_diff - 200.0) < 2 * bin_width, (
            f"Frequency difference {freq_diff:.1f} Hz, expected ~200 Hz "
            f"(tolerance {2*bin_width:.1f} Hz)")

    def test_frequency_prior_confines_reported_candidates(self):
        frequency_mask = np.abs(Wf) <= 200.0
        detections, _, best_candidate = _run_detect(
            self.K, snr_db=25.0, freq_offset_hz=1200.0, seed=50,
            frequency_mask=frequency_mask)

        assert all(abs(detection.freq_hz) <= 200.0 for detection in detections)
        if not detections:
            assert best_candidate is not None
            assert abs(best_candidate['freq_hz']) <= 200.0

    def test_frequency_mask_rejects_non_bool_and_wrong_shape(self):
        # An int mask would fancy-index best_scores rather than select bins.
        with pytest.raises(ValueError, match='must be'):
            _run_detect(self.K, snr_db=25.0, seed=50,
                        frequency_mask=(np.abs(Wf) <= 200.0).astype(np.int64))
        with pytest.raises(ValueError, match='must be'):
            _run_detect(self.K, snr_db=25.0, seed=50,
                        frequency_mask=(np.abs(Wf) <= 200.0).tolist())
        with pytest.raises(ValueError, match='does not match'):
            _run_detect(self.K, snr_db=25.0, seed=50,
                        frequency_mask=np.ones(len(Wf) - 1, dtype=bool))
        with pytest.raises(ValueError, match='selects no bins'):
            _run_detect(self.K, snr_db=25.0, seed=50,
                        frequency_mask=np.zeros(len(Wf), dtype=bool))

    @pytest.mark.parametrize('offset_hz', [0.0, 200.0, -500.0, 1200.0])
    def test_absolute_frequency_label(self, offset_hz):
        """Reported freq_hz must be the true baseband offset, not merely
        correct relative to another detection (regression: a double fftshift
        in build_weighting_matrix relabelled every bin by Fs/2)."""
        dets, _, _ = _run_detect(self.K, snr_db=25.0, freq_offset_hz=offset_hz, seed=71)
        assert len(dets) >= 1
        f = max(dets, key=lambda d: d[1])[0]
        bin_width = FS / NFFT
        assert abs(f - offset_hz) < 2 * bin_width, (
            f"Reported {f:+.1f} Hz for a tone at {offset_hz:+.1f} Hz")

    def test_noise_only_no_detection(self):
        detections, noise_psd, _ = _run_detect(self.K, snr_db=-np.inf, seed=99)
        assert len(detections) == 0, "Noise-only segment should produce no detections"
        assert np.isfinite(noise_psd), "Noise PSD should be finite"

    def test_moderate_signal_detected(self):
        detections, _, _ = _run_detect(self.K, snr_db=12.0, seed=7)
        assert len(detections) >= 1, "Moderate signal (12 dB) should be detected with K=5"

    def test_fold_info_present(self):
        detections, _, _ = _run_detect(self.K, snr_db=25.0)
        assert len(detections) >= 1
        assert 'max_fold_fraction' in detections[0].fold_info
        assert 'fold_snrs' in detections[0].fold_info
        assert len(detections[0].fold_info['fold_snrs']) == self.K

    def test_negative_freq_offset(self):
        """A negative offset should produce a detection at a lower
        frequency than a zero-offset signal (modulo spectral wrapping)."""
        d0, _, _ = _run_detect(self.K, snr_db=20.0, freq_offset_hz=0.0, seed=60)
        dn, _, _ = _run_detect(self.K, snr_db=20.0, freq_offset_hz=-500.0, seed=60)
        assert len(d0) >= 1 and len(dn) >= 1
        f0 = max(d0, key=lambda d: d[1])[0]
        fn = max(dn, key=lambda d: d[1])[0]
        raw_diff = fn - f0
        # Wrap to [-FS/2, FS/2) to handle spectral boundary crossing
        wrapped_diff = ((raw_diff + FS / 2) % FS) - FS / 2
        bin_width = FS / NFFT
        assert abs(wrapped_diff - (-500.0)) < 2 * bin_width, (
            f"Wrapped frequency shift {wrapped_diff:.1f} Hz, expected ~-500 Hz")

    def test_detection_margin_tight(self):
        """Tight margin (0.99) should still detect a strong signal."""
        detections, _, _ = _run_detect(self.K, snr_db=25.0, detection_margin=0.99)
        assert len(detections) >= 1

    def test_reproducibility(self):
        d1, _, _ = _run_detect(self.K, snr_db=20.0, seed=123)
        d2, _, _ = _run_detect(self.K, snr_db=20.0, seed=123)
        assert len(d1) == len(d2)
        if d1:
            assert d1[0][0] == pytest.approx(d2[0][0])
            assert d1[0][1] == pytest.approx(d2[0][1])


