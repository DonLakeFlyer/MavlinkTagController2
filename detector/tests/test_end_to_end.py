# Rate-switch helpers
# ===================================================================
_NOISE_POWER_DBFS = -40.0   # Same noise floor as SimConfig default


def _generate_rate_switch_iq(K: int, snr_db: float, change_point: int,
                             direction: str = 'A_to_B',
                             freq_offset_hz: float = 0.0,
                             seed: int = 42) -> tuple[np.ndarray, int]:
    """Generate IQ with a rate switch at the given change-point.

    Args:
        change_point: Number of gaps at the first rate before switching.
            0 = pure second rate, K-1 = pure first rate.
        direction: 'A_to_B' (rest→move) or 'B_to_A' (move→rest).

    Returns:
        (iq, samples_needed) tuple.
    """
    if direction == 'A_to_B':
        spacings_sec = ([TIP_REST] * change_point
                        + [TIP_MOVE] * (K - 1 - change_point))
    else:
        spacings_sec = ([TIP_MOVE] * change_point
                        + [TIP_REST] * (K - 1 - change_point))

    samples_needed = compute_segment_samples(N_WS, N_OL, K, N_EXACT, N_EXACT_MOVE)

    rng = np.random.default_rng(seed)
    noise_sigma = 10.0 ** (_NOISE_POWER_DBFS / 20.0)
    noise = noise_sigma * (
        rng.standard_normal(samples_needed)
        + 1j * rng.standard_normal(samples_needed)
    ) / np.sqrt(2.0)

    signal = np.zeros(samples_needed, dtype=np.complex128)
    if np.isfinite(snr_db):
        # Build pulse start times from spacing schedule
        pulse_times = [0.0]
        for s in spacings_sec:
            pulse_times.append(pulse_times[-1] + s)

        snr_linear = 10.0 ** (snr_db / 10.0)
        amp = noise_sigma * np.sqrt(snr_linear)
        t = np.arange(samples_needed, dtype=np.float64) / FS
        tone = amp * np.exp(2j * np.pi * freq_offset_hz * t)
        pulse_len = int(np.ceil(TP * FS))
        for pt in pulse_times:
            start = int(round(pt * FS))
            end = min(start + pulse_len, samples_needed)
            if start < samples_needed:
                signal[start:end] = tone[start:end]

    return (signal + noise).astype(np.complex64), samples_needed


def _run_detect_rate_switch(K: int, snr_db: float, change_point: int,
                            direction: str = 'A_to_B',
                            freq_offset_hz: float = 0.0,
                            seed: int = 42,
                            detection_margin: float = 0.90):
    """Full pipeline with multi-hypothesis fold_detect."""
    old_K = pulse_detector.K
    pulse_detector.K = K
    try:
        iq, samples_needed = _generate_rate_switch_iq(
            K, snr_db, change_point, direction, freq_offset_hz, seed)

        power, n_win = compute_stft_power(iq, N_W, N_OL, NFFT, W=W)
        hyps = build_hypothesis_indices(N_EXACT, K, n_win, N_B=N_EXACT_MOVE)

        fo = _fold_offsets(K, TIP_REST)
        cache = _evt_pool.setdefault((K, N_MOVE), {})

        return fold_detect(
            power, N, PF, FS, NFFT, N_W, N_OL, samples_needed,
            cache,
            fold_offsets=fo,
            W=W, Wf=Wf,
            detection_margin=detection_margin,
            hypotheses=hyps, N_B=N_MOVE,
        )
    finally:
        pulse_detector.K = old_K


