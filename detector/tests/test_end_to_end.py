# STFT geometry (mirrors pulse_detector main())
N_W = int(np.ceil(TP * FS))               # 58 samples
N_OL = N_W // 2                            # 29 samples
N_WS = N_W - N_OL                          # 29 samples (window step)
N_EXACT = TIP_REST * FS / N_WS            # fractional PRI in windows
N = int(np.floor(N_EXACT))                # integer PRI (resting rate)
N_EXACT_MOVE = TIP_MOVE * FS / N_WS
