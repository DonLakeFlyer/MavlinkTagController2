def _fold_offsets(K: int, tip: float = TIP_A) -> np.ndarray:
    N_exact = tip * FS / N_WS
    return np.round(np.arange(K) * N_exact).astype(int)


def _generate_segment(K: int, snr_db: float, freq_offset_hz: float = 0.0,
                      tip: float = TIP_A, seed: int = 42) -> np.ndarray:
    """Generate a continuous IQ segment covering K pulse intervals."""
    N_A_exact = tip * FS / N_WS
    samples_needed = compute_segment_samples(N_WS, N_OL, K, N_A_exact)

    cfg = SimConfig(
        sample_rate=FS,
        samples_per_packet=samples_needed,
        noise_power_dbfs=-40.0,
        tags=[TagSignal(
            freq_offset_hz=freq_offset_hz,
            snr_db=snr_db,
            tp=TP,
            tip=tip,
        )],
        seed=seed,
    )
    rng = np.random.default_rng(cfg.seed)
    return generate_packet(cfg, sample_offset=0, rng=rng, telem_state=None)


def _run_detect(K: int, snr_db: float, freq_offset_hz: float = 0.0,
                tip: float = TIP_A, seed: int = 42,
                detection_margin: float = 1.0, frequency_mask=None,
                max_detections: int = 1, extra_tags=()):
    """Full pipeline: generate IQ → STFT → fold_detect. Returns fold_detect output."""
    old_K = pulse_detector.K
    pulse_detector.K = K
    try:
        N_A_exact = tip * FS / N_WS
        fo = _fold_offsets(K, tip)
        samples_needed = compute_segment_samples(N_WS, N_OL, K, N_A_exact)
        if extra_tags:
            cfg = SimConfig(
                sample_rate=FS, samples_per_packet=samples_needed,
                noise_power_dbfs=-40.0,
                tags=[TagSignal(freq_offset_hz=freq_offset_hz, snr_db=snr_db,
                                tp=TP, tip=tip)] + list(extra_tags),
                seed=seed)
            iq = generate_packet(cfg, sample_offset=0,
                                 rng=np.random.default_rng(seed), telem_state=None)
        else:
            iq = _generate_segment(K, snr_db, freq_offset_hz, tip, seed)

        power, n_win = compute_stft_power(iq, N_W, N_OL, NFFT, W=W)

        return fold_detect(
            power, N, PF, FS, NFFT, N_W, N_OL, samples_needed,
            {'rng': np.random.default_rng(seed)},
            fold_offsets=fo,
            W=W, Wf=Wf,
            detection_margin=detection_margin,
            frequency_mask=frequency_mask,
            max_detections=max_detections,
        )
    finally:
        pulse_detector.K = old_K


def test_fold_detect_rejects_geometry_that_disagrees_with_k_folds():
    # k_folds keys the EVT threshold: a mismatch with the folded geometry
    # would silently apply the wrong false-alarm threshold.
    power = np.ones((NFFT, 3000), dtype=np.float32)
    offsets_k5 = _fold_offsets(5, TIP_A)
    with pytest.raises(ValueError, match='fold_offsets has 5 folds but k_folds=20'):
        fold_detect(power, N, PF, FS, NFFT, N_W, N_OL, 1, {},
                    fold_offsets=offsets_k5, W=W, Wf=Wf, k_folds=20)
    hyps_k5 = build_hypothesis_indices(N_EXACT, 5, 3000, N_EXACT_B)
    with pytest.raises(ValueError, match=r'built for \[5\] folds but k_folds=20'):
        fold_detect(power, N, PF, FS, NFFT, N_W, N_OL, 1, {},
                    hypotheses=hyps_k5, W=W, Wf=Wf, k_folds=20)
    with pytest.raises(ValueError, match='k_folds must be >= 1'):
        fold_detect(power, N, PF, FS, NFFT, N_W, N_OL, 1, {},
                    fold_offsets=offsets_k5, W=W, Wf=Wf, k_folds=0)


def test_fold_detect_returns_extra_peaks_only_when_asked():
    # Two trains 1 kHz apart: the default single-peak result keeps reports
    # single, while the candidate bank asks for the alternates.
    second = TagSignal(freq_offset_hz=1000.0, snr_db=20.0, tp=TP, tip=TIP_A)
    single, _, _ = _run_detect(5, snr_db=25.0, seed=91, extra_tags=[second])
    assert len(single) == 1
    assert abs(single[0].freq_hz) < 100.0

    multi, _, _ = _run_detect(5, snr_db=25.0, seed=91, extra_tags=[second],
                              max_detections=4)
    # At 25 dB a spectral sidelobe may also clear the threshold, so only the
    # ordering and the two real trains are asserted.
    assert 2 <= len(multi) <= 4
    assert abs(multi[0].freq_hz) < 100.0            # strongest first
    assert any(abs(d.freq_hz - 1000.0) < 100.0 for d in multi[1:])
    assert all(multi[i].snr_db >= multi[i + 1].snr_db
               for i in range(len(multi) - 1))


# ===================================================================
# K = 5 (default fold count)
# ===================================================================
class TestSingleRateK5:
    K = 5

    def test_strong_signal_detected(self):
        detections, _, _ = _run_detect(self.K, snr_db=25.0)
        assert len(detections) >= 1, "Strong signal (25 dB) should be detected"

    def test_strong_signal_snr_reasonable(self):
        detections, _, _ = _run_detect(self.K, snr_db=25.0)
        best = max(detections, key=lambda d: d[1])
        assert best[1] > 10.0, f"Detected SNR {best[1]:.1f} dB unexpectedly low"

    def test_strong_signal_frequency_accuracy(self):
        """Two signals at different offsets should produce detections
        separated by the correct frequency difference."""
        d1, _, _ = _run_detect(self.K, snr_db=25.0, freq_offset_hz=0.0, seed=50)
        d2, _, _ = _run_detect(self.K, snr_db=25.0, freq_offset_hz=200.0, seed=50)
        assert len(d1) >= 1 and len(d2) >= 1
        f1 = max(d1, key=lambda d: d[1])[0]
        f2 = max(d2, key=lambda d: d[1])[0]
        freq_diff = f2 - f1
        bin_width = FS / NFFT
        assert abs(freq_diff - 200.0) < 2 * bin_width, (
            f"Frequency difference {freq_diff:.1f} Hz, expected ~200 Hz "
            f"(tolerance {2*bin_width:.1f} Hz)")

    def test_frequency_prior_confines_reported_candidates(self):
        frequency_mask = np.abs(Wf) <= 200.0
        detections, _, best_candidate = _run_detect(
            self.K, snr_db=25.0, freq_offset_hz=1200.0, seed=50,
            frequency_mask=frequency_mask)

        assert all(abs(detection.freq_hz) <= 200.0 for detection in detections)
        if not detections:
            assert best_candidate is not None
            assert abs(best_candidate['freq_hz']) <= 200.0

    def test_frequency_mask_rejects_non_bool_and_wrong_shape(self):
        # An int mask would fancy-index best_scores rather than select bins.
        with pytest.raises(ValueError, match='must be'):
            _run_detect(self.K, snr_db=25.0, seed=50,
                        frequency_mask=(np.abs(Wf) <= 200.0).astype(np.int64))
        with pytest.raises(ValueError, match='must be'):
            _run_detect(self.K, snr_db=25.0, seed=50,
                        frequency_mask=(np.abs(Wf) <= 200.0).tolist())
        with pytest.raises(ValueError, match='does not match'):
            _run_detect(self.K, snr_db=25.0, seed=50,
                        frequency_mask=np.ones(len(Wf) - 1, dtype=bool))
        with pytest.raises(ValueError, match='selects no bins'):
            _run_detect(self.K, snr_db=25.0, seed=50,
                        frequency_mask=np.zeros(len(Wf), dtype=bool))

    @pytest.mark.parametrize('offset_hz', [0.0, 200.0, -500.0, 1200.0])
    def test_absolute_frequency_label(self, offset_hz):
        """Reported freq_hz must be the true baseband offset, not merely
        correct relative to another detection (regression: a double fftshift
        in build_weighting_matrix relabelled every bin by Fs/2)."""
        dets, _, _ = _run_detect(self.K, snr_db=25.0, freq_offset_hz=offset_hz, seed=71)
